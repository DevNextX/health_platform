class TestMemberIsolation:
    def test_two_users_cannot_see_each_others_histories(self, client):
        h1 = _register_and_login(client, "iso1")
        h2 = _register_and_login(client, "iso2")
        mid1 = _get_self_member_id(client, h1)
        mid2 = _get_self_member_id(client, h2)

        _create(client, h1, mid1, disease_name="User1 Disease")
        _create(client, h2, mid2, disease_name="User2 Disease")

        # User 1 should only see their own
        resp1 = client.get(f"{BASE}?member_id={mid1}", headers=h1)
        assert resp1.get_json()["pagination"]["total"] == 1
        assert resp1.get_json()["histories"][0]["disease_name"] == "User1 Disease"

        # User 2 should only see their own
        resp2 = client.get(f"{BASE}?member_id={mid2}", headers=h2)
        assert resp2.get_json()["pagination"]["total"] == 1
        assert resp2.get_json()["histories"][0]["disease_name"] == "User2 Disease"
