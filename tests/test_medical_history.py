def _register_and_login(client, suffix: str = "") -> dict:
    client.post(
        "/api/v1/auth/register",
        json={
            "username": f"user{suffix}",
            "email": f"user{suffix}@example.com",
            "password": "password123",
            "age": 30,
            "gender": "male",
            "weight": 70,
        },
    )
    resp = client.post(
        "/api/v1/auth/login",
        json={"email": f"user{suffix}@example.com", "password": "password123"},
    )
    data = resp.get_json()
    return {"Authorization": f"Bearer {data['access_token']}"}


def _get_self_member_id(client, headers: dict) -> int:
    resp = client.get("/api/v1/members", headers=headers)
    members = resp.get_json()["members"]
    assert len(members) >= 1
    return members[0]["id"]


def _create(client, headers, member_id, **overrides):
    payload = {
        "member_id": member_id,
        "disease_name": "Hypertension",
        "onset_date": "2020-01-15",
        "is_ongoing": True,
        "is_on_medication": False,
        **overrides,
    }
    return client.post(BASE, json=payload, headers=headers)


