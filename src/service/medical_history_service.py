    if errors:
        return jsonify(error("400", "Validation error", details=errors)), 400

    h = manager.create(
        household_id=member.household_id,
        member_id=member_id,
        disease_name=clean["disease_name"],
        onset_date=clean["onset_date"],
        description=clean.get("description"),
        is_ongoing=clean["is_ongoing"],
        is_on_medication=clean["is_on_medication"],
        created_by_user_id=user_id,
    )
    return jsonify(_serialize(h)), 201


