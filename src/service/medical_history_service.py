@medical_history_bp.route("/<int:history_id>/attachments/<int:attachment_id>/download", methods=["GET"])
@jwt_required()
def download_attachment(history_id: int, attachment_id: int):
    user_id = get_jwt_identity()
    household = member_mgr.get_household(user_id)
    if not household:
        return jsonify(error("404", "Household not found")), 404
    history = manager.get_by_household(history_id, household.id)
    if not history:
        return jsonify(error("404", "Medical history not found")), 404
    item = attachment_mgr.get(attachment_id, history_id, household.id)
    if not item:
        return jsonify(error("404", "Attachment not found")), 404

    file_path = attachment_mgr.get_full_path(item.storage_key)
    if not file_path.exists():
        return jsonify(error("404", "Attachment file not found")), 404

    ascii_name = f"attachment_{item.id}{item.file_ext}"
    with open(file_path, "rb") as fh:
        payload = fh.read()
    resp = Response(payload, mimetype=item.mime_type)
    resp.headers["Content-Disposition"] = (
        f"attachment; filename=\"{ascii_name}\"; filename*=UTF-8''{quote(item.file_name)}"
    )
    return resp


