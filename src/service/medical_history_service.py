    errors = {}

    # disease_name
    if not for_update or "disease_name" in data:
        val = (data.get("disease_name") or "").strip()
        if not val:
            if not for_update:
                errors["disease_name"] = ["required"]
        elif len(val) > 120:
            errors["disease_name"] = ["max 120 characters"]
        else:
            clean["disease_name"] = val

    # onset_date  (YYYY-MM-DD)
    if not for_update or "onset_date" in data:
        raw = data.get("onset_date")
        if not raw:
            if not for_update:
                errors["onset_date"] = ["required"]
        else:
            try:
                if isinstance(raw, str):
                    clean["onset_date"] = date.fromisoformat(raw.strip())
                else:
                    errors["onset_date"] = ["must be a date string (YYYY-MM-DD)"]
            except ValueError:
                errors["onset_date"] = ["must be a valid date (YYYY-MM-DD)"]

    # description  (optional)
    if "description" in data:
        clean["description"] = data["description"] or None

    # is_ongoing  (boolean)
    if not for_update or "is_ongoing" in data:
        val = data.get("is_ongoing")
        if not for_update and val is None:
            errors["is_ongoing"] = ["required"]
        elif val is not None:
            if not isinstance(val, bool):
                errors["is_ongoing"] = ["must be a boolean"]
            else:
                clean["is_ongoing"] = val

    # is_on_medication  (boolean)
    if not for_update or "is_on_medication" in data:
        val = data.get("is_on_medication")
        if not for_update and val is None:
            errors["is_on_medication"] = ["required"]
        elif val is not None:
            if not isinstance(val, bool):
                errors["is_on_medication"] = ["must be a boolean"]
            else:
                clean["is_on_medication"] = val

    return clean, errors


