def _validate_payload(data: dict, for_update: bool = False) -> tuple[dict, dict]:
    """Validate create / update payload. Returns (clean, errors)."""
    clean = {}
    errors = {}

    # disease_name
    if not for_update or "disease_name" in data:
        val = (data.get("disease_name") or "").strip()
        if not val:
            if not for_update:
                errors["disease_name"] = ["required"]
        elif len(val) > 120:
            errors["disease_name"] = ["max 120 characters"]
        else:
            clean["disease_name"] = val

    # onset_date  (YYYY-MM-DD)
    if not for_update or "onset_date" in data:
        raw = data.get("onset_date")
        if not raw:
            if not for_update:
                errors["onset_date"] = ["required"]
        else:
            try:
                if isinstance(raw, str):
                    clean["onset_date"] = date.fromisoformat(raw.strip())
                else:
                    errors["onset_date"] = ["must be a date string (YYYY-MM-DD)"]
            except ValueError:
                errors["onset_date"] = ["must be a valid date (YYYY-MM-DD)"]

    # description  (optional)
    if "description" in data:
        clean["description"] = data["description"] or None

    # is_ongoing  (boolean)
    if not for_update or "is_ongoing" in data:
        val = data.get("is_ongoing")
        if not for_update and val is None:
            errors["is_ongoing"] = ["required"]
        elif val is not None:
            if not isinstance(val, bool):
                errors["is_ongoing"] = ["must be a boolean"]
            else:
                clean["is_ongoing"] = val

    # is_on_medication  (boolean)
    if not for_update or "is_on_medication" in data:
        val = data.get("is_on_medication")
        if not for_update and val is None:
            errors["is_on_medication"] = ["required"]
        elif val is not None:
            if not isinstance(val, bool):
                errors["is_on_medication"] = ["must be a boolean"]
            else:
                clean["is_on_medication"] = val

    return clean, errors


def _validate_attachment(file) -> tuple[dict, dict]:
    clean = {}
    errors = {}
    filename = (file.filename or "").strip()
    if not filename:
        return clean, {"file": ["filename is required"]}
    ext = Path(filename).suffix.lower()
    allowed = {
        x.strip().lower()
        for x in (current_app.config.get("ATTACHMENT_ALLOWED_EXT", ".jpg,.jpeg,.png,.pdf,.doc,.docx") or "").split(",")
        if x.strip()
    }
    if ext not in allowed:
        errors["file"] = [f"unsupported extension: {ext or 'unknown'}"]
    mime = (file.mimetype or "application/octet-stream").lower()
    allowed_mime = {
        ".jpg": {"image/jpeg"},
        ".jpeg": {"image/jpeg"},
        ".png": {"image/png"},
        ".pdf": {"application/pdf"},
        ".doc": {"application/msword"},
        ".docx": {"application/vnd.openxmlformats-officedocument.wordprocessingml.document"},
    }
    expected = allowed_mime.get(ext, set())
    if expected and mime not in expected and mime != "application/octet-stream":
        errors["file"] = [f"unsupported mime type: {mime}"]
    file.seek(0, 2)
    size = file.tell()
    file.seek(0)
    max_size = int(current_app.config.get("ATTACHMENT_MAX_FILE_SIZE_MB", 20)) * 1024 * 1024
    if size <= 0:
        errors["file"] = ["file is empty"]
    elif size > max_size:
        errors["file"] = [f"file size exceeds {current_app.config.get('ATTACHMENT_MAX_FILE_SIZE_MB', 20)}MB limit"]
    clean = {"file_name": filename, "file_ext": ext, "mime_type": mime, "file_size": size}
    return clean, errors


