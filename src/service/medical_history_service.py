@medical_history_bp.route("", methods=["POST"])
@jwt_required()
def create_history():
    user_id = get_jwt_identity()
    data = request.get_json(force=True) or {}

    # Ownership check
    member_id_raw = data.get("member_id")
    if member_id_raw is None:
        return jsonify(error("400", "member_id is required")), 400
    try:
        member_id = int(member_id_raw)
    except (TypeError, ValueError):
        return jsonify(error("400", "member_id must be an integer")), 400

    member = member_mgr.get_member(user_id, member_id)
    if not member:
        return jsonify(error("404", "Member not found")), 404

