def _serialize_record(rec):
    """Serialize a HealthRecord to dict."""
    return {
        "id": rec.id,
        "systolic": rec.systolic,
        "diastolic": rec.diastolic,
        "heart_rate": rec.heart_rate,
        "timestamp": _format_timestamp(rec.timestamp),
        "tags": json.loads(rec.tags) if rec.tags else [],
        "note": rec.note,
        "created_at": _format_timestamp(rec.created_at)
    }


def _parse_int(value):
    if value is None:
        raise TypeError("missing")
    if isinstance(value, int):
        return value
    # Reject floats and numeric-like strings with decimals
    if isinstance(value, float):
        raise ValueError("not integer")
    if isinstance(value, str) and value.strip() != "" and value.isdigit():
        return int(value)
    # For strings like "120.5" or non-digits, raise
    raise ValueError("invalid format")


def _parse_iso_datetime(value) -> datetime:
    """Parse ISO8601-ish timestamps from clients and return a datetime."""
    if isinstance(value, datetime):
        return value
    if not isinstance(value, str):
        raise TypeError("timestamp must be a string")
    normalized = value.strip()
    if not normalized:
        raise ValueError("empty timestamp")
    if "T" not in normalized and " " in normalized:
        normalized = normalized.replace(" ", "T", 1)
    if normalized[-1:] in ("Z", "z"):
        normalized = normalized[:-1] + "+00:00"
    try:
        return datetime.fromisoformat(normalized)
    except ValueError as exc:
        raise ValueError("invalid timestamp format") from exc


def _ensure_utc(dt: datetime) -> datetime:
    if dt.tzinfo is None:
        return dt.replace(tzinfo=UTC)
    return dt.astimezone(UTC)


def _as_db_datetime(dt: datetime) -> datetime:
    """Convert to naive UTC for storage/filters (DB columns are naive)."""
    return _ensure_utc(dt).replace(tzinfo=None)


def _format_timestamp(value: datetime) -> str:
    if value is None:
        return ""
    utc_dt = _ensure_utc(value)
    return utc_dt.isoformat().replace("+00:00", "Z")


def _validate_health_record_payload(data, for_update=False, current=None):
    """Validate payload for create/update. Return (clean, errors)."""
    errors = {}
    clean = {}

    # systolic
    if not for_update or ("systolic" in data):
        val = data.get("systolic")
        if val is None or (isinstance(val, str) and val.strip() == ""):
            if not for_update:
                errors.setdefault("systolic", []).append("required")
        else:
            try:
                s = _parse_int(val)
                if not (30 <= s <= 250):
                    errors.setdefault("systolic", []).append("must be between 30-250")
                else:
                    clean["systolic"] = s
            except (TypeError, ValueError):
                errors.setdefault("systolic", []).append("must be an integer")

    # diastolic
    if not for_update or ("diastolic" in data):
        val = data.get("diastolic")
        if val is None or (isinstance(val, str) and val.strip() == ""):
            if not for_update:
                errors.setdefault("diastolic", []).append("required")
        else:
            try:
                d = _parse_int(val)
                if not (30 <= d <= 250):
                    errors.setdefault("diastolic", []).append("must be between 30-250")
                else:
                    clean["diastolic"] = d
            except (TypeError, ValueError):
                errors.setdefault("diastolic", []).append("must be an integer")

    # heart_rate optional; allow explicit empty to clear on update
    if ("heart_rate" in data) or not for_update:
        val = data.get("heart_rate")
        if val is None or (isinstance(val, str) and val.strip() == ""):
            clean["heart_rate"] = None
        else:
            try:
                hr = _parse_int(val)
                if not (30 <= hr <= 150):
                    errors.setdefault("heart_rate", []).append("must be between 30-150")
                else:
                    clean["heart_rate"] = hr
            except (TypeError, ValueError):
                errors.setdefault("heart_rate", []).append("must be an integer")

    # relation check when both values are known (from payload or current)
    s_eff = clean.get("systolic") if "systolic" in clean else (current.systolic if current and hasattr(current, "systolic") else None)
    d_eff = clean.get("diastolic") if "diastolic" in clean else (current.diastolic if current and hasattr(current, "diastolic") else None)
    if s_eff is not None and d_eff is not None:
        if s_eff <= d_eff:
            errors.setdefault("_schema", []).append("systolic must be greater than diastolic")

    return clean, errors


@health_bp.route("", methods=["POST"])
@jwt_required()
def create_record():
    user_id = get_jwt_identity()
    data = request.get_json(force=True) or {}

    clean, errors = _validate_health_record_payload(data, for_update=False)
    if errors:
        return jsonify(error("400", "Validation error", details=errors)), 400

    systolic = clean.get("systolic")
    diastolic = clean.get("diastolic")
    heart_rate = clean.get("heart_rate")
    ts_raw = data.get("timestamp")
    if ts_raw:
        try:
            ts = _as_db_datetime(_parse_iso_datetime(ts_raw))
        except (TypeError, ValueError):
            return jsonify(error("400", "Invalid timestamp")), 400
    else:
        ts = _as_db_datetime(datetime.now(UTC))
    tags = data.get("tags") or []
    if not isinstance(tags, list):
        return jsonify(error("400", "Validation error", details={"tags": ["must be a list"]})), 400
    note = data.get("note")

    # Determine subject member (default to self member if not provided)
    subject_member_id = data.get("subject_member_id")
    if subject_member_id is not None:
        try:
            subject_member_id = int(subject_member_id)
        except (TypeError, ValueError):
            return jsonify(error("400", "Invalid subject_member_id")), 400
        # Validate member belongs to current user's household
        m = member_mgr.get_member(user_id, subject_member_id)
        if not m or m.status != "active":
            return jsonify(error("404", "Member not found")), 404
    else:
        m = member_mgr.get_or_create_self_member(user_id)
        subject_member_id = m.id

    rec = manager.create(user_id=user_id, systolic=systolic, diastolic=diastolic, heart_rate=heart_rate,
                         timestamp=ts, tags=tags, note=note)
    # Link record to subject
    rs = RecordSubject()
    hh = member_mgr.ensure_default_household(user_id)
    rs.record_id = rec.id
    rs.household_id = hh.id
    rs.member_id = subject_member_id
    rs.created_by_user_id = user_id
    from ..extensions import db
    db.session.add(rs)
    db.session.commit()
    
    result = _serialize_record(rec)
    result["subject_member_id"] = subject_member_id
    return jsonify(result), 201


