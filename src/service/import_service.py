"""
Import service endpoints for health record batch import. Generated by Copilot
"""
from flask import Blueprint, request, jsonify
from flask_jwt_extended import jwt_required, get_jwt_identity
from werkzeug.utils import secure_filename
import os
from ..manager.import_manager import ImportManager
from ..utils import error

import_bp = Blueprint("import", __name__)
manager = ImportManager()

# File upload constraints
MAX_FILE_SIZE = 5 * 1024 * 1024  # 5MB
MAX_ROWS = 1000
ALLOWED_EXTENSIONS = {'.xlsx', '.xls', '.csv'}


def _get_file_extension(filename: str) -> str:
    """Get file extension from filename."""
    return os.path.splitext(filename)[1].lower()


def _validate_file(file):
    """
    Validate uploaded file.
    
    Returns:
        Tuple of (is_valid, error_message, file_extension)
    """
    if not file:
        return False, "未上传文件", None
    
    if not file.filename:
        return False, "文件名为空", None
    
    # Check file extension
    ext = _get_file_extension(file.filename)
    if ext not in ALLOWED_EXTENSIONS:
        return False, f"不支持的文件格式，仅支持: {', '.join(ALLOWED_EXTENSIONS)}", None
    
    # Read file content to check size
    file.seek(0, os.SEEK_END)
    file_size = file.tell()
    file.seek(0)  # Reset to beginning
    
    if file_size > MAX_FILE_SIZE:
        return False, f"文件大小超过限制 ({MAX_FILE_SIZE / 1024 / 1024:.1f}MB)", None
    
    if file_size == 0:
        return False, "文件为空", None
    
    return True, None, ext


@import_bp.route("/api/v1/import/upload", methods=["POST"])
@jwt_required()
def upload_import_file():
    """
    Upload and import health records from Excel/CSV file.
    
    Request:
        - Content-Type: multipart/form-data
        - file: Excel or CSV file (required)
        - skip_errors: Boolean, whether to skip error rows (optional, default: true)
    
    Response 200:
        {
            "message": "导入完成",
            "total": 100,
            "success": 95,
            "failed": 5,
            "errors": [
                {"row": 10, "reason": "成员名称不存在"},
                ...
            ]
        }
    
    Response 400: Invalid file or format
    Response 401: Unauthorized
    """
    user_id = get_jwt_identity()
    
    # Get uploaded file
    if 'file' not in request.files:
        return jsonify(error("400", "请上传文件")), 400
    
    file = request.files['file']
    
    # Validate file
    is_valid, error_msg, file_ext = _validate_file(file)
    if not is_valid:
        return jsonify(error("400", error_msg)), 400
    
    # Get skip_errors parameter (default: True)
    skip_errors_str = request.form.get('skip_errors', 'true').lower()
    skip_errors = skip_errors_str in ['true', '1', 'yes']
    
    try:
        # Parse file
        rows = manager.parse_file(file.stream, file_ext)
        
        if not rows:
            return jsonify(error("400", "文件中没有数据")), 400
        
        # Check row limit
        if len(rows) > MAX_ROWS:
            return jsonify(error("400", f"文件行数超过限制 ({MAX_ROWS} 行)")), 400
        
        # Batch import
        result = manager.batch_import(user_id, rows, skip_errors)
        
        # Save import log
        filename = secure_filename(file.filename)
        manager.save_import_log(user_id, filename, result)
        
        # Prepare response
        response_data = {
            "message": "导入完成",
            "total": result['total'],
            "success": result['success'],
            "failed": result['failed']
        }
        
        # Include error details if any
        if result['errors']:
            # Limit error details in response (only first 100)
            response_data['errors'] = [
                {
                    "row": err['row'],
                    "reason": err['reason']
                }
                for err in result['errors'][:100]
            ]
            
            if len(result['errors']) > 100:
                response_data['message'] += f"（仅显示前 100 个错误）"
        
        return jsonify(response_data), 200
        
    except ValueError as e:
        return jsonify(error("400", str(e))), 400
    except Exception as e:
        return jsonify(error("500", f"导入失败: {str(e)}")), 500
