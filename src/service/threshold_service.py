@bp.route("/admin/thresholds/draft", methods=["POST"])
@jwt_required()
@require_role("SUPER_ADMIN")
def create_draft():
    """Create a new draft threshold profile (SUPER_ADMIN only)."""
    payload = request.get_json(force=True)
    metadata = _get_request_metadata()
    
    try:
        # Support two formats:
        # 1. Simplified format from SuperAdminSettings: {"thresholds": {"systolic": {"lower": 90, "upper": 120}, ...}}
        # 2. Full format: {"systolic_healthy": [90, 120], "systolic_borderline": [120, 140], ...}
        
        if "thresholds" in payload:
            # Convert simplified format to full format
            thresholds = payload["thresholds"]
            systolic = thresholds.get("systolic", {})
            diastolic = thresholds.get("diastolic", {})
            heart_rate = thresholds.get("heart_rate", {})
            
            # Generate healthy and borderline ranges
            # Healthy range: user-defined lower to upper
            # Borderline range: upper to upper+20 (default extension)
            full_payload = {
                "systolic_healthy": [systolic.get("lower", 90), systolic.get("upper", 120)],
                "systolic_borderline": [systolic.get("upper", 120), systolic.get("upper", 120) + 20],
                "diastolic_healthy": [diastolic.get("lower", 60), diastolic.get("upper", 80)],
                "diastolic_borderline": [diastolic.get("upper", 80), diastolic.get("upper", 80) + 10],
                "systolic_min": systolic.get("lower", 90),
                "systolic_max": systolic.get("upper", 120) + 20,
                "diastolic_min": diastolic.get("lower", 60),
                "diastolic_max": diastolic.get("upper", 80) + 10,
            }
            
            if heart_rate.get("lower") and heart_rate.get("upper"):
                full_payload["heart_rate_min"] = heart_rate["lower"]
                full_payload["heart_rate_max"] = heart_rate["upper"]
            
            payload = full_payload
        
        draft = manager.create_draft(payload, **metadata)
        return jsonify(draft), 201
    except ThresholdValidationError as e:
        return jsonify({"error": str(e)}), 400
    except Exception as e:
        return jsonify({"error": "Failed to create draft", "details": str(e)}), 500


