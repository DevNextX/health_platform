@bp.route("/admin/thresholds/audit/export", methods=["GET"])
@jwt_required()
@require_role("SUPER_ADMIN", "ADMIN")
def export_audit_logs():
    """Export audit logs as CSV."""
    from_date = request.args.get("from")
    to_date = request.args.get("to")
    action = request.args.get("action")
    
    from_dt = datetime.fromisoformat(from_date) if from_date else None
    to_dt = datetime.fromisoformat(to_date) if to_date else None
    
    try:
        logs = manager.get_audit_logs(from_date=from_dt, to_date=to_dt, action=action, limit=10000)
        
        output = io.StringIO()
        output.write('\ufeff')
        
        writer = csv.DictWriter(output, fieldnames=[
            "id", "action", "actor_id", "config_id", "created_at"
        ])
        writer.writeheader()
        
        for log in logs:
            writer.writerow({
                "id": log.id,
                "action": log.action,
                "actor_id": log.actor_id,
                "config_id": log.config_id,
                "created_at": log.created_at.isoformat()
            })
        
        csv_data = output.getvalue()
        output.close()
        
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        filename = f"threshold_audit_{timestamp}.csv"
        
        response = Response(csv_data, mimetype="text/csv; charset=utf-8")
        response.headers["Content-Disposition"] = f"attachment; filename*=UTF-8''{filename}"
        
        return response
        
    except Exception as e:
        return jsonify({"error": "Export failed", "details": str(e)}), 500
