    def validate_profile(self, payload: Dict[str, Any]) -> None:
        """Validate systolic/diastolic/heart_rate ranges according to project rules.

        Rules:
        - systolic and diastolic required and between 30 and 250
        - systolic > diastolic
        - heart_rate if present between 30 and 150
        """
        s_min = payload.get("systolic_min")
        s_max = payload.get("systolic_max")
        d_min = payload.get("diastolic_min")
        d_max = payload.get("diastolic_max")
        hr_min = payload.get("heart_rate_min")
        hr_max = payload.get("heart_rate_max")

        def between(v, a, b):
            return v is not None and a <= v <= b

        if s_min is None or s_max is None or d_min is None or d_max is None:
            raise ThresholdValidationError("systolic/diastolic ranges are required")
        if not (between(s_min, 30, 250) and between(s_max, 30, 250)):
            raise ThresholdValidationError("systolic values must be between 30 and 250")
        if not (between(d_min, 30, 250) and between(d_max, 30, 250)):
            raise ThresholdValidationError("diastolic values must be between 30 and 250")
        # Allow boundaries to touch (e.g., systolic_min == diastolic_max)
        if s_min < d_max:
            raise ThresholdValidationError("systolic must not be less than diastolic ranges")
        if hr_min is not None and not between(hr_min, 30, 150):
            raise ThresholdValidationError("heart_rate_min must be between 30 and 150")
        if hr_max is not None and not between(hr_max, 30, 150):
            raise ThresholdValidationError("heart_rate_max must be between 30 and 150")

