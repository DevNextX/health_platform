        """
        Validate configuration payload.
        Expected format:
        {
            "systolic": {"min": 90, "max": 120, "borderline_max": 140},
            "diastolic": {"min": 60, "max": 80, "borderline_max": 90},
            "heart_rate": {"min": 60, "max": 100}
        }
        """
        # Hard limits
        LIMITS = {
            "systolic": (30, 250),
            "diastolic": (30, 250),
            "heart_rate": (30, 150)
        }

        required_keys = ["systolic", "diastolic", "heart_rate"]
        for key in required_keys:
            if key not in payload:
                raise ThresholdValidationError(f"Missing required key: {key}")
            
            item = payload[key]
            if not isinstance(item, dict) or "min" not in item or "max" not in item:
                raise ThresholdValidationError(f"Invalid format for {key}, expected {{'min': x, 'max': y}}")
            
            val_min = item["min"]
            val_max = item["max"]
            val_borderline = item.get("borderline_max")
            
            limit_min, limit_max = LIMITS[key]
            
            if not (isinstance(val_min, (int, float)) and isinstance(val_max, (int, float))):
                 raise ThresholdValidationError(f"{key} values must be numbers")

            if val_min < limit_min or val_max > limit_max:
                raise ThresholdValidationError(f"{key} values must be between {limit_min} and {limit_max}")
            
            if val_min >= val_max:
                raise ThresholdValidationError(f"{key} min must be less than max")
            
            # Validate borderline_max for blood pressure metrics
            if key in ["systolic", "diastolic"]:
                if val_borderline is None:
                    raise ThresholdValidationError(f"{key} must have borderline_max")
                if not isinstance(val_borderline, (int, float)):
                    raise ThresholdValidationError(f"{key} borderline_max must be a number")
                if val_borderline > limit_max:
                    raise ThresholdValidationError(f"{key} borderline_max must be between {limit_min} and {limit_max}")
                if val_borderline <= val_max:
                    raise ThresholdValidationError(f"{key} borderline_max must be greater than max")

        # Cross-field validation
        sys_min = payload["systolic"]["min"]
        dia_max = payload["diastolic"]["max"]
        if sys_min < dia_max:
             raise ThresholdValidationError("Systolic min must be greater than Diastolic max")

