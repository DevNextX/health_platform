    def _compute_status(self, systolic: int, diastolic: int, heart_rate: Optional[int], payload: Dict[str, Any]) -> str:
        """Compute threshold status based on ranges in payload."""
        # Extract ranges from payload
        # Expected format: { systolic_healthy: [90, 120], systolic_borderline: [120, 140], ... }
        s_healthy = payload.get("systolic_healthy", [90, 120])
        s_borderline = payload.get("systolic_borderline", [120, 140])
        d_healthy = payload.get("diastolic_healthy", [60, 80])
        d_borderline = payload.get("diastolic_borderline", [80, 90])
        
        # Logic: if both in healthy range -> healthy
        #        if either in borderline -> borderline
        #        otherwise -> out_of_range
        s_status = "out_of_range"
        if s_healthy[0] <= systolic <= s_healthy[1]:
            s_status = "healthy"
        elif s_borderline[0] <= systolic <= s_borderline[1]:
            s_status = "borderline"
        
        d_status = "out_of_range"
        if d_healthy[0] <= diastolic <= d_healthy[1]:
            d_status = "healthy"
        elif d_borderline[0] <= diastolic <= d_borderline[1]:
            d_status = "borderline"
        
        # Combine: worst status wins
        if s_status == "out_of_range" or d_status == "out_of_range":
            return "out_of_range"
        if s_status == "borderline" or d_status == "borderline":
            return "borderline"
        return "healthy"

    def publish(self, draft_id: int, actor_id: int, actor_ip: str = None, user_agent: str = None) -> Dict[str, Any]:
        """Transactionally publish a draft as the active profile.
        
        Steps:
        1. Validate draft exists and is in draft status
        2. Archive current active profile (if any)
        3. Mark draft as active and set effective_at
        4. Increment global threshold_version
        5. Create immutable ThresholdVersion record
        6. Write audit log
        7. Commit transaction
        """
        profile = ThresholdProfile.query.filter_by(id=draft_id, status="draft").first()
        if not profile:
            raise ValueError(f"Draft {draft_id} not found or not in draft status")
        
        try:
            # Archive current active profile
            current_active = ThresholdProfile.query.filter_by(status="active").first()
            before_payload = None
            if current_active:
                before_payload = current_active.payload
                current_active.status = "archived"
            
            # Mark draft as active
            profile.status = "active"
            profile.effective_at = datetime.now(UTC)
            
            # Increment global threshold_version
            config = SystemConfig.query.filter_by(key="threshold_version").first()
            if not config:
                config = SystemConfig(key="threshold_version", value="1")
                db.session.add(config)
                new_version = 1
            else:
                new_version = int(config.value) + 1
                config.value = str(new_version)
            
            # Create immutable version record
            version_record = ThresholdVersion(
                version=new_version,
                profile_id=profile.id,
                payload_snapshot=profile.payload,
                published_by=actor_id
            )
            db.session.add(version_record)
            
            # Write audit log
            audit = ThresholdAuditLog(
                action="publish",
                actor_id=actor_id,
                actor_ip=actor_ip,
                actor_user_agent=user_agent,
                before_payload=before_payload,
                after_payload=profile.payload,
                profile_id=profile.id,
                version=new_version
            )
            db.session.add(audit)
            
            db.session.commit()
            
            return {
                "version": new_version,
                "published_at": profile.effective_at.isoformat(),
                "profile_id": profile.id
            }
        except Exception as e:
            db.session.rollback()
            raise

