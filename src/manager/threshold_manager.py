    def _compute_status(self, systolic: int, diastolic: int, heart_rate: Optional[int], payload: Dict[str, Any]) -> str:
        """
        Compute threshold status based on ranges in payload.
        Three-tier status model:
        - healthy: All values within [min, max]
        - borderline: Any BP value in (max, borderline_max] (but none out_of_range)
        - out_of_range: Any value outside all defined ranges
        """
        s_range = payload.get("systolic")
        d_range = payload.get("diastolic")
        hr_range = payload.get("heart_rate")
        
        has_out_of_range = False
        has_borderline = False
        
        # Check systolic
        if s_range:
            if systolic < s_range["min"] or systolic > s_range.get("borderline_max", s_range["max"]):
                has_out_of_range = True
            elif systolic > s_range["max"]:
                has_borderline = True
        
        # Check diastolic
        if d_range:
            if diastolic < d_range["min"] or diastolic > d_range.get("borderline_max", d_range["max"]):
                has_out_of_range = True
            elif diastolic > d_range["max"]:
                has_borderline = True
        
        # Check heart rate (no borderline zone)
        if heart_rate is not None and hr_range:
            if heart_rate < hr_range["min"] or heart_rate > hr_range["max"]:
                has_out_of_range = True
        
        if has_out_of_range:
            return "out_of_range"
        elif has_borderline:
            return "borderline"
        else:
            return "healthy"

